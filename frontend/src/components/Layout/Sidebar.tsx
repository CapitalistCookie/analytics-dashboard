export default function Sidebar() {
  const { user, logout, isAuthenticated } = useAuth()
  const { setMobileMenuOpen, isMobile } = useLayout()
  const navigate = useNavigate()

  const handleNavClick = () => {
    if (isMobile) {
      setMobileMenuOpen(false)
    }
  }

  const handleLogout = () => {
    logout()
    if (isMobile) {
      setMobileMenuOpen(false)
    }
  }

  const handleKioskMode = () => {
    setMobileMenuOpen(false)
    navigate('/kiosk')
  }

  return (
    <aside className="w-64 bg-gray-800 min-h-screen p-4 flex flex-col">
      {/* Header with close button on mobile */}
      <div className="mb-8 flex items-center justify-between">
        <div>
          <h1 className="text-xl font-bold text-white">Analytics</h1>
          <p className="text-sm text-gray-400">Restaurant Dashboard</p>
        </div>
        {/* Close button - mobile only */}
        <button
          onClick={() => setMobileMenuOpen(false)}
          className="md:hidden p-2 text-gray-400 hover:text-white hover:bg-gray-700 rounded-lg transition-colors"
          aria-label="Close menu"
        >
          <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
          </svg>
        </button>
      </div>

      <nav className="space-y-1 md:space-y-2 flex-1">
        {navItems.map((item) => (
          <NavLink
            key={item.path}
            to={item.path}
            onClick={handleNavClick}
            className={({ isActive }) =>
              `flex items-center gap-3 px-4 py-3 rounded-lg transition-colors touch-manipulation ${
                isActive
                  ? 'bg-blue-600 text-white'
                  : 'text-gray-300 hover:bg-gray-700 active:bg-gray-600'
              }`
            }
          >
            <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={item.icon} />
            </svg>
            <span className="truncate">{item.label}</span>
          </NavLink>
        ))}

        {/* Admin-only items */}
        {user?.role === 'admin' && (
          <>
            <div className="pt-4 mt-4 border-t border-gray-700">
              <p className="px-4 text-xs font-semibold text-gray-500 uppercase mb-2">Admin</p>
            </div>
            {adminNavItems.map((item) => (
              <NavLink
                key={item.path}
                to={item.path}
                onClick={handleNavClick}
                className={({ isActive }) =>
                  `flex items-center gap-3 px-4 py-3 rounded-lg transition-colors touch-manipulation ${
                    isActive
                      ? 'bg-blue-600 text-white'
                      : 'text-gray-300 hover:bg-gray-700 active:bg-gray-600'
                  }`
                }
              >
                <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={item.icon} />
                </svg>
                <span className="truncate">{item.label}</span>
              </NavLink>
            ))}
          </>
        )}

        {/* Kiosk mode button - in sidebar for mobile access */}
        <div className="pt-4 mt-4 border-t border-gray-700 md:hidden">
          <button
            onClick={handleKioskMode}
            className="w-full flex items-center gap-3 px-4 py-3 text-gray-300 hover:bg-gray-700 active:bg-gray-600 rounded-lg transition-colors touch-manipulation"
          >
            <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9.75 17L9 20l-1 1h8l-1-1-.75-3M3 13h18M5 17h14a2 2 0 002-2V5a2 2 0 00-2-2H5a2 2 0 00-2 2v10a2 2 0 002 2z" />
            </svg>
            Kiosk Mode
          </button>
        </div>
      </nav>

      {/* User section */}
      {isAuthenticated && user && (
        <div className="pt-4 border-t border-gray-700">
          <NavLink
            to="/profile"
            onClick={handleNavClick}
            className={({ isActive }) =>
              `flex items-center gap-3 px-4 py-2 mb-2 rounded-lg transition-colors touch-manipulation ${
                isActive ? 'bg-gray-700' : 'hover:bg-gray-700 active:bg-gray-600'
              }`
            }
          >
            <div className="w-8 h-8 bg-blue-600 rounded-full flex items-center justify-center text-white font-medium flex-shrink-0">
              {user.username.charAt(0).toUpperCase()}
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium text-white truncate">{user.username}</p>
              <p className="text-xs text-gray-400 capitalize">{user.role}</p>
            </div>
          </NavLink>
          <button
            onClick={handleLogout}
            className="w-full flex items-center gap-3 px-4 py-2 text-gray-300 hover:bg-gray-700 active:bg-gray-600 rounded-lg transition-colors touch-manipulation"
          >
            <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
            </svg>
            Logout
          </button>
        </div>
      )}
    </aside>
  )
}
